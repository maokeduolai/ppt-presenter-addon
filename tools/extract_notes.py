#!/usr/bin/env python3
"""Convert page-grouped Markdown into language-neutral, plain-text JS notes.

Only page headings are interpreted. Other Markdown is retained as plain text.
No third-party Python dependencies or playback build step is required.
"""
import argparse
import json
from pathlib import Path
import re

PAGE = re.compile(r'^##\s+(?:Slide\s+(\d+)|第\s*(\d+)\s*页)\s*[|｜:：]\s*(.*?)\s*$', re.I)
FENCE = re.compile(r'^\s*(`{3,}|~{3,})')


def parse_notes(text):
    slides, lines, current, fence = [], [], None, None

    def flush():
        if current is not None:
            current['text'] = '\n'.join(lines).strip()
            slides.append(current.copy())
        lines.clear()

    for line in text.splitlines():
        marker = FENCE.match(line)
        if marker:
            token = marker[1]
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence) and not line.strip()[len(token):].strip():
                fence = None
        heading = PAGE.match(line) if fence is None and not marker else None
        if heading:
            flush()
            number = int(heading[1] or heading[2])
            if number != len(slides) + 1:
                raise ValueError(f'Expected page {len(slides) + 1}, got {number}')
            current = {'title':heading[3], 'text':''}
        elif current is not None:
            lines.append(line)
    flush()
    if not slides:
        raise ValueError('No page headings found. Use: ## Slide 1 | Title')
    return slides


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    source, output = args.source.resolve(), args.output.resolve()
    if source == output or output.suffix != '.js':
        parser.error('Output must be a separate .js file.')
    try:
        data = {'slides':parse_notes(source.read_text(encoding='utf-8-sig'))}
        encoded = json.dumps(data, ensure_ascii=False, indent=2).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
        output.write_text('// Generated by tools/extract_notes.py\nwindow.HTMLPresenterNotes = ' + encoded + ';\n', encoding='utf-8')
    except (OSError, UnicodeError, ValueError) as error:
        parser.error(str(error))
    print(f'Wrote {len(data["slides"])} slide notes to {output}')


if __name__ == '__main__':
    main()
